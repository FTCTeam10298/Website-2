import { ACTIONS } from './actions';
import { fmt, reversedForStep } from './geometry';
import type { Auto, PlannerState, Pose, Step } from './types';

export function sanitize(s: string | undefined) { return (s || '').trim().replace(/[^A-Za-z0-9_]/g, '_'); }

function pose(p: Pose) {
  return `new Pose2D(${fmt(p.x)}, ${fmt(p.y)}, Math.toRadians(${fmt(p.h)}))`;
}

function genStep(st: Step, i: number, auto: Auto) {
  if (st.kind === 'move') {
    if (st.move === 'goto')
      return `drive.goToPoint(${pose(st)}, ${st.through}, ${fmt(st.maxSpeed)});\ndriveToTarget();`;
    const rev = st.reversed != null ? st.reversed : reversedForStep(i, auto.steps, auto.start);
    return `drive.splineToPoint(${pose(st)}, ${st.through}, ${rev}, ${fmt(st.factor)}, ${fmt(st.maxSpeed)});\ndriveToTarget();`;
  }
  if (st.kind === 'action') return ACTIONS[st.type].gen(st);
  return '';
}

// Walks the flat step list, emitting for/if/else/} blocks with nested indentation.
function genBodyFor(auto: Auto, baseIndent: string, withSetPos: boolean) {
  const out: string[] = [];
  if (withSetPos) out.push(baseIndent + `localizer.setPosition(${pose(auto.start)});`);
  let depth = 0;
  const ind = () => baseIndent + '    '.repeat(depth);
  auto.steps.forEach((st, i) => {
    if (st.kind === 'repeat') {
      const v = st.var || 'i';
      out.push(`${ind()}for (int ${v} = 0; ${v} < ${Math.max(0, Math.round(st.count) || 0)}; ${v}++) {`);
      depth++;
    } else if (st.kind === 'if') {
      out.push(`${ind()}if (${st.cond || 'true'}) {`); depth++;
    } else if (st.kind === 'else') {
      depth = Math.max(0, depth - 1); out.push(`${ind()}} else {`); depth++;
    } else if (st.kind === 'end') {
      depth = Math.max(0, depth - 1); out.push(`${ind()}}`);
    } else {
      genStep(st, i, auto).split('\n').forEach(line => out.push(ind() + line));
    }
  });
  return out.join('\n');
}

function genMethod(state: PlannerState) {
  const auto = state.autos[state.activeAuto];
  const name = sanitize(auto.name) || 'My_Auto';
  return [
    '// ===== Generated by Neuron Path Planner =====',
    '// Paste into an OpMode in your season repo that already has:',
    '//   - `drive` (NeuronDrive) / `localizer` (NeuronLocalizer) + driveToTarget()/waitMs()',
    '//     helpers (see NeuronSplineAuto.java for the pattern), for the movement calls, and',
    '//   - `robot` (your season\'s Robot facade) + shoot()/farShoot()/pulseOuttake() helpers',
    '//     and an `alliance` field (-1 Blue / +1 Red), for the shoot/intake/gate/turret calls.',
    '// Or switch this tool to "Full OpMode" output to generate all of that scaffolding too.',
    `public void ${name}() {`,
    genBodyFor(auto, '    ', state.includeSetPos),
    '}',
  ].join('\n');
}

function genOpMode(state: PlannerState) {
  const cls = sanitize(state.opModeName) || 'auto';
  const autos = state.autos;
  // Each auto becomes: a selectable name, an init-loop start pose (by index), a
  // run-time switch case, and its own method—mirroring NeuronSplineAuto.java.
  const namesArr = autos.map(a => `            "${(a.label || a.name).replace(/"/g, '\\"')}",`).join('\n');
  const initCases = autos.map((a, i) =>
`                case ${i}:
                    localizer.setPosition(${pose(a.start)});
                    break;`).join('\n');
  const runCases = autos.map((a, i) =>
`            case ${i}:
                ${sanitize(a.name) || ('Auto' + i)}();
                break;`).join('\n');
  const methods = autos.map(a => [
`    public void ${sanitize(a.name) || 'Auto'}() {`,
genBodyFor(a, '        ', false),
`    }`].join('\n')).join('\n\n');
  return [
`package org.firstinspires.ftc.teamcode.opmodes;`,
``,
`import com.qualcomm.robotcore.eventloop.opmode.Autonomous;`,
`import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;`,
``,
`import org.firstinspires.ftc.teamcode.Robot;                       // your season's subsystem facade`,
`import org.firstinspires.ftc.teamcode.subsystems.turret.Turret;    // for shoot/intake/gate/turret actions`,
`import org.firstinspires.ftc.teamcode.utils.CONSTANTS;`,
`import org.firstinspires.ftc.teamcode.neuronpathing.NeuronDrive;`,
`import org.firstinspires.ftc.teamcode.neuronpathing.NeuronLocalizer;`,
`import org.firstinspires.ftc.teamcode.neuronpathing.Pose2D;`,
``,
`// ===== Generated by Neuron Path Planner =====`,
`// TODO set the Pinpoint offsets (xOffsetMm/yOffsetMm) and NeuronDrive trackWidthIn`,
`// below for your own robot (Installation/Tuning docs). Movement runs on the Neuron`,
`// Pathing library directly (drive/localizer); shoot/intake/gate/turret actions still`,
`// go through this season's Robot facade—drop the Robot/Turret/CONSTANTS imports`,
`// above (and the action calls below) if your OpMode doesn't need them.`,
`@Autonomous(name = "${cls}")`,
`public class ${cls} extends LinearOpMode {`,
`    Robot robot;`,
`    NeuronLocalizer localizer;`,
`    NeuronDrive drive;`,
`    int alliance = -1; // -1 = Blue, +1 = Red—for subsystems; paths are the same for both`,
`    int autoIndex = 0;`,
`    String[] autoNames = {`,
namesArr,
`    };`,
``,
`    @Override`,
`    public void runOpMode() throws InterruptedException {`,
`        robot = new Robot(hardwareMap, telemetry, this);`,
`        localizer = new NeuronLocalizer(hardwareMap, telemetry, /*xOffsetMm=*/0, /*yOffsetMm=*/0);`,
`        drive = new NeuronDrive(hardwareMap, localizer, /*trackWidthIn=*/14);`,
`        robot.turret.turretState = Turret.TurretState.AUTO;`,
`        robot.gate.close();`,
`        localizer.calibrate(true);`,
``,
`        while (opModeInInit() && !isStopRequested()) {`,
`            if (gamepad1.x) { CONSTANTS.alliance = CONSTANTS.Alliance.BLUE; alliance = -1; }`,
`            else if (gamepad1.b) { CONSTANTS.alliance = CONSTANTS.Alliance.RED; alliance = 1; }`,
`            CONSTANTS.updateGoal();`,
``,
`            if (gamepad1.dpadUpWasPressed()) { autoIndex++; }`,
`            else if (gamepad1.dpadDownWasPressed()) { autoIndex--; }`,
`            autoIndex = (autoIndex + autoNames.length) % autoNames.length;`,
``,
`            switch (autoIndex) {`,
initCases,
`            }`,
``,
`            robot.turret.update();`,
`            telemetry.addLine("===== AUTO SELECT =====");`,
`            telemetry.addData("Alliance", alliance == -1 ? "Blue" : "Red");`,
`            telemetry.addData("Auto", autoNames[autoIndex]);`,
`            telemetry.addLine("DPAD UP/DOWN = change auto, X/B = Blue/Red");`,
`            telemetry.update();`,
`        }`,
``,
`        waitForStart();`,
`        if (isStopRequested()) return;`,
``,
`        switch (autoIndex) {`,
runCases,
`        }`,
`    }`,
``,
methods,
``,
`    // Blocks until the active goToPoint()/splineToPoint() move finishes. NeuronDrive`,
`    // only moves while update() is being called, so every move needs one of these.`,
`    private void driveToTarget() {`,
`        while (opModeIsActive() && drive.isBusy()) {`,
`            drive.update();`,
`            robot.turret.update();`,
`            telemetry.update();`,
`            idle();`,
`        }`,
`    }`,
``,
`    // Pauses for ms milliseconds while still actively holding position.`,
`    private void waitMs(double ms) {`,
`        double start = System.currentTimeMillis();`,
`        while (opModeIsActive() && System.currentTimeMillis() - start < ms) {`,
`            drive.update();`,
`            robot.turret.update();`,
`            idle();`,
`        }`,
`    }`,
``,
`    public void shoot() {`,
`        waitMs(100);`,
`        robot.gate.open();`,
`        robot.intake.shoot();`,
`        waitMs(500);`,
`        robot.gate.close();`,
`        robot.intake.in();`,
`    }`,
``,
`    public void farShoot() {`,
`        waitMs(300);`,
`        robot.gate.open();`,
`        robot.intake.farzoneshoot();`,
`        waitMs(500);`,
`        robot.gate.close();`,
`        robot.intake.in();`,
`    }`,
``,
`    public void pulseOuttake(int ms) {`,
`        robot.intake.out();`,
`        waitMs(ms);`,
`        robot.intake.in();`,
`    }`,
`}`,
  ].join('\n');
}

export function generateCode(state: PlannerState) {
  return state.output === 'opmode' ? genOpMode(state) : genMethod(state);
}
